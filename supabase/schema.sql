-- GameFilter relational schema.
-- Run in Supabase SQL Editor after creating the project.

-- Public profile data is separated from auth.users so reviews can safely show avatars/names.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 60),
  avatar_url text,
  bio text not null default '' check (char_length(bio) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.library_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  game_id integer not null,
  game_name text not null check (char_length(game_name) between 1 and 200),
  game_slug text not null check (char_length(game_slug) between 1 and 220),
  background_image text,
  status text not null check (status in ('want_to_play', 'playing', 'completed', 'dropped')),
  favorite boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint one_library_row_per_game unique (user_id, game_id)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  game_id integer not null,
  game_name text not null check (char_length(game_name) between 1 and 200),
  score integer not null check (score between 1 and 10),
  recommended boolean not null,
  body text not null check (char_length(body) between 10 and 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- This is the hard guarantee: one account can never own two reviews for one game.
  constraint one_review_per_user_per_game unique (user_id, game_id)
);

create table if not exists public.review_helpful_votes (
  review_id bigint not null references public.reviews(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (review_id, user_id)
);

create index if not exists reviews_game_id_idx on public.reviews(game_id);
create index if not exists library_user_id_idx on public.library_entries(user_id);
create index if not exists helpful_review_id_idx on public.review_helpful_votes(review_id);

create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(new.email, '@', 1), 'Player')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Backfill profiles for users created before this schema existed.
insert into public.profiles (id, display_name)
select id, coalesce(nullif(trim(raw_user_meta_data ->> 'display_name'), ''), split_part(email, '@', 1), 'Player')
from auth.users
on conflict (id) do nothing;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at before update on public.profiles
for each row execute function public.touch_updated_at();

drop trigger if exists reviews_touch_updated_at on public.reviews;
create trigger reviews_touch_updated_at before update on public.reviews
for each row execute function public.touch_updated_at();

drop trigger if exists library_touch_updated_at on public.library_entries;
create trigger library_touch_updated_at before update on public.library_entries
for each row execute function public.touch_updated_at();

-- Public review feed keeps presentation fields together without duplicating profile data.
create or replace view public.review_feed
with (security_invoker = true) as
select
  r.id,
  r.user_id,
  r.game_id,
  r.game_name,
  r.score,
  r.recommended,
  r.body,
  r.created_at,
  r.updated_at,
  p.display_name,
  p.avatar_url,
  count(v.user_id)::integer as helpful_count
from public.reviews r
join public.profiles p on p.id = r.user_id
left join public.review_helpful_votes v on v.review_id = r.id
group by r.id, p.display_name, p.avatar_url;

create or replace view public.game_review_stats
with (security_invoker = true) as
select
  game_id,
  count(*)::integer as review_count,
  round(avg(score) * 10)::integer as score,
  round(100.0 * count(*) filter (where recommended) / nullif(count(*), 0))::integer as recommended_percent
from public.reviews
group by game_id;

alter table public.profiles enable row level security;
alter table public.library_entries enable row level security;
alter table public.reviews enable row level security;
alter table public.review_helpful_votes enable row level security;

-- Profiles are public because reviews display names and avatars; only owners can mutate them.
drop policy if exists "profiles public read" on public.profiles;
drop policy if exists "users insert own profile" on public.profiles;
drop policy if exists "users update own profile" on public.profiles;
create policy "profiles public read" on public.profiles for select using (true);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- Libraries are private and always scoped to the signed-in user.
drop policy if exists "users read own library" on public.library_entries;
drop policy if exists "users create own library" on public.library_entries;
drop policy if exists "users update own library" on public.library_entries;
drop policy if exists "users delete own library" on public.library_entries;
create policy "users read own library" on public.library_entries for select to authenticated using (auth.uid() = user_id);
create policy "users create own library" on public.library_entries for insert to authenticated with check (auth.uid() = user_id);
create policy "users update own library" on public.library_entries for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users delete own library" on public.library_entries for delete to authenticated using (auth.uid() = user_id);

-- Reviews are public to read; only their author can create, edit, or delete them.
drop policy if exists "reviews public read" on public.reviews;
drop policy if exists "users create own reviews" on public.reviews;
drop policy if exists "users update own reviews" on public.reviews;
drop policy if exists "users delete own reviews" on public.reviews;
create policy "reviews public read" on public.reviews for select using (true);
create policy "users create own reviews" on public.reviews for insert to authenticated with check (auth.uid() = user_id);
create policy "users update own reviews" on public.reviews for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users delete own reviews" on public.reviews for delete to authenticated using (auth.uid() = user_id);

-- Helpful votes are public to count; each user can only manage their own vote.
drop policy if exists "helpful votes public read" on public.review_helpful_votes;
drop policy if exists "users create own helpful votes" on public.review_helpful_votes;
drop policy if exists "users delete own helpful votes" on public.review_helpful_votes;
create policy "helpful votes public read" on public.review_helpful_votes for select using (true);
create policy "users create own helpful votes" on public.review_helpful_votes for insert to authenticated with check (auth.uid() = user_id);
create policy "users delete own helpful votes" on public.review_helpful_votes for delete to authenticated using (auth.uid() = user_id);

grant select on public.profiles, public.reviews, public.review_helpful_votes, public.review_feed, public.game_review_stats to anon, authenticated;
grant insert, update on public.profiles to authenticated;
grant insert, update, delete on public.reviews to authenticated;
grant select, insert, update, delete on public.library_entries to authenticated;
grant insert, delete on public.review_helpful_votes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Public avatar bucket. Object write policies below still restrict uploads to each user's folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "avatar public read" on storage.objects;
drop policy if exists "users upload own avatar" on storage.objects;
drop policy if exists "users update own avatar" on storage.objects;
drop policy if exists "users delete own avatar" on storage.objects;
create policy "avatar public read" on storage.objects for select using (bucket_id = 'avatars');
create policy "users upload own avatar" on storage.objects for insert to authenticated
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "users update own avatar" on storage.objects for update to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "users delete own avatar" on storage.objects for delete to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
